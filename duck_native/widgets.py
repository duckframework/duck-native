"""
Finds a project's custom Kotlin widgets and wires them into the copied Android project.
"""

import re
import shutil

from pathlib import Path

from duck.logging import console

from duck_native.actions import ActionError, BUILT_IN, KOTLIN_DIR, NAME, PACKAGE
from duck_native.config import ProjectConfig


# Build some directories
WIDGETS_DIR = Path("native") / "widgets"

# Regular Expressions
ANNOTATION = re.compile(rf'^@DuckWidget\("({NAME})"\)\s+class\s+(\w+)', re.MULTILINE)


class WidgetError(ActionError):
    """
    Raised when a custom widget cannot be registered.
    """


def find_widgets(widgets_dir: Path) -> list[tuple[str, str]]:
    """
    Find every @DuckWidget class in a folder.

    Args:
        widgets_dir: Folder with the user's .kt files.

    Returns:
        list[tuple[str, str]]: Pairs of widget name and the fully qualified class name.

    Raises:
        WidgetError: If a file declares a class without a package.
    """
    found = []

    for path in sorted(widgets_dir.rglob("*.kt")):
        text = path.read_text(encoding="utf-8")
        package = PACKAGE.search(text)

        for name, class_name in ANNOTATION.findall(text):
            if package is None:
                raise WidgetError(f"{path.name} needs a package line, e.g. package com.example.myapp")

            # Add widget
            found.append((name, f"{package.group(1)}.{class_name}"))

    return found


def install_widgets(config: ProjectConfig, target: Path) -> None:
    """
    Copy the user's widgets into the Android project and register them.

    Args:
        config: The validated project config.
        target: The copied Android project.

    Raises:
        WidgetError: If a name is used twice or clashes with a built-in widget.
    """
    widgets_dir = config.project_dir / WIDGETS_DIR

    if not widgets_dir.is_dir():
        return

    # Find widgets
    widgets = find_widgets(widgets_dir)

    if not widgets:
        return

    # Names must be unique, including the built-in ones.
    registry = (target / KOTLIN_DIR / "NativeWidgetRegistry.kt").read_text(encoding="utf-8")
    taken = set(BUILT_IN.findall(registry))

    for name, _ in widgets:
        if name in taken:
            raise WidgetError(f"Widget name '{name}' is already used. Pick another.")

        # Add taken widget name
        taken.add(name)

    # Copy the sources next to the bridge code.
    custom_dir = target / KOTLIN_DIR / "custom"

    # Log something
    console.log(f"Copying custom widgets to {custom_dir}", level=console.DEBUG)

    # Make dir
    custom_dir.mkdir(parents=True, exist_ok=True)

    for path in widgets_dir.rglob("*.kt"):
        shutil.copyfile(path, custom_dir / path.name)

    # Generate the registration code.
    lines = "".join(
        f'    registry.register("{name}") {{ {class_name}() }}\n'
        for name, class_name in widgets
    )

    for name, _ in widgets:
        console.log(f"Registering widget {name}", level=console.DEBUG)

    (target / KOTLIN_DIR / "CustomWidgets.kt").write_text(
        "package com.duckframework.bridge\n\n"
        "/**\n * Generated by Duck Native. Do not edit.\n */\n"
        f"fun registerCustomWidgets(registry: NativeWidgetRegistry) {{\n{lines}}}\n",
        encoding="utf-8",
    )
