"""
Finds a project's custom Kotlin actions and wires them into the copied Android project.
"""

import re
import shutil

from pathlib import Path

from duck.logging import console

from duck_native.config import ProjectConfig


# Build some directories
ACTIONS_DIR = Path("native") / "actions"
KOTLIN_DIR = Path("app") / "src" / "main" / "java" / "com" / "duckframework" / "bridge"

# Regular Expressions
NAME = r"[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)*"
ANNOTATION = re.compile(rf'^@DuckAction\("({NAME})"\)\s+(class|object)\s+(\w+)', re.MULTILINE)
PACKAGE = re.compile(r"^package\s+([\w.]+)", re.MULTILINE)
BUILT_IN = re.compile(r'registry\.register\("([^"]+)"')


class ActionError(Exception):
    """
    Raised when a custom action cannot be registered.
    """


def find_actions(actions_dir: Path) -> list[tuple[str, str]]:
    """
    Find every @DuckAction class in a folder.

    Args:
        actions_dir: Folder with the user's .kt files.

    Returns:
        list[tuple[str, str]]: Pairs of action name and Kotlin expression that creates it, e.g. ("flashlight.toggle", "my.app.Flash()").

    Raises:
        ActionError: If a file declares a class without a package.
    """
    found = []

    for path in sorted(actions_dir.rglob("*.kt")):
        text = path.read_text(encoding="utf-8")
        package = PACKAGE.search(text)

        for name, kind, class_name in ANNOTATION.findall(text):
            if package is None:
                raise ActionError(f"{path.name} needs a package line, e.g. package com.example.myapp")
            
            call = "" if kind == "object" else "()"
            
            # Add action
            found.append((name, f"{package.group(1)}.{class_name}{call}"))
    
    return found


def install_actions(config: ProjectConfig, target: Path) -> None:
    """
    Copy the user's actions into the Android project and register them.

    Args:
        config: The validated project config.
        target: The copied Android project.

    Raises:
        ActionError: If a name is used twice or clashes with a built-in action.
    """
    actions_dir = config.project_dir / ACTIONS_DIR
    
    if not actions_dir.is_dir():
        return

    # Find actions
    actions = find_actions(actions_dir)
    
    if not actions:
        return

    # Names must be unique, including the built-in ones.
    registry = (target / KOTLIN_DIR / "NativeActionRegistry.kt").read_text(encoding="utf-8")
    taken = set(BUILT_IN.findall(registry))
    
    for name, _ in actions:
        if name in taken:
            raise ActionError(f"Action name '{name}' is already used. Pick another.")
        
        # Add taken action name
        taken.add(name)

    # Copy the sources next to the bridge code.
    custom_dir = target / KOTLIN_DIR / "custom"
    
    # Log something
    console.log(f"Copying custom actions to {custom_dir}", level=console.DEBUG)
    
    # Make dir
    custom_dir.mkdir(parents=True, exist_ok=True)
    
    for path in actions_dir.rglob("*.kt"):
        shutil.copyfile(path, custom_dir / path.name)

    # Generate the registration code.
    lines = "".join(
        f'    registry.register("{name}", {expression})\n'
        for name, expression in actions
    )
    
    for name, _ in actions:
        console.log(f"Registering action {name}", level=console.DEBUG)

    (target / KOTLIN_DIR / "CustomActions.kt").write_text(
        "package com.duckframework.bridge\n\n"
        "/**\n * Generated by Duck Native. Do not edit.\n */\n"
        f"fun registerCustomActions(registry: NativeActionRegistry) {{\n{lines}}}\n",
        encoding="utf-8",
    )
